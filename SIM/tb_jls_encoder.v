//--------------------------------------------------------------------------------------------------------
// Module  : tb_jls_encoder
// Type    : simulation, top
// Standard: Verilog 2001 (IEEE1364-2001)
// Function: testbench for jls_encoder,
//           load some .pgm files (uncompressed image file), and push them to jls_encoder.
//           get output JPEG-LS stream from jls_encoder, and write them to .jls files (JPEG-LS image file)
//
// Modes (pass via iverilog -D flag, e.g. -D SELF_CHECK):
//   default         : compress images, write .jls to OUTPUT_JLS_DIR
//   -D SELF_CHECK   : also byte-compare every frame against GOLDEN_JLS_DIR
//                     (run_sim.py generates these goldens with CharLS, an
//                     independent JPEG-LS implementation)
//
// The run fails ($fatal, non-zero exit) on any mismatch, missing golden,
// output shorter or longer than its golden, unreadable input/output file,
// or a frame that does not complete within FRAME_TIMEOUT_CYCLES.
//
// Overridable defines (pass via iverilog -D, or via sim_config.vh):
//   NEAR            : 0~7 (default 0)
//   MAX_WIDTH       : jls_encoder MAX_WIDTH parameter (default 16384)
//   FILE_NO_FIRST   : first file number (default 1)
//   FILE_NO_FINAL   : last file number (default 23)
//   BUBBLE_CONTROL  : bubble insertion control (default -1)
//   OUTPUT_JLS_DIR  : where encoder output is written (default ".")
//--------------------------------------------------------------------------------------------------------

`timescale 1ps/1ps

// sim_config.vh is generated by run_sim.py before each compile.
// If running manually without run_sim.py, the defaults below apply.
`ifdef HAVE_SIM_CONFIG
`include "sim_config.vh"
`endif

`ifndef NEAR
`define NEAR            0
`endif
`ifndef MAX_WIDTH
`define MAX_WIDTH       16384
`endif
`ifndef BUBBLE_CONTROL
`define BUBBLE_CONTROL  (-1)
`endif
`ifndef GOLDEN_JLS_DIR
`define GOLDEN_JLS_DIR  "./golden"
`endif
`ifndef FILE_NO_FIRST
`define FILE_NO_FIRST   1
`endif
`ifndef FILE_NO_FINAL
`define FILE_NO_FINAL   23
`endif
`ifndef OUTPUT_JLS_DIR
`define OUTPUT_JLS_DIR  "."
`endif
`ifndef FRAME_TIMEOUT_CYCLES
`define FRAME_TIMEOUT_CYCLES 100000
`endif

`define FILE_NAME_FORMAT  "test%03d"
`define INPUT_PGM_DIR     "./images"


module tb_jls_encoder ();

//initial $dumpvars(1, tb_jls_encoder);

// -------------------------------------------------------------------------------------------------------------------
//   generate clock and reset
// -------------------------------------------------------------------------------------------------------------------
reg          rstn = 1'b0;
reg           clk = 1'b0;
always #50000 clk = ~clk;  // 10MHz
initial begin repeat(4) @(posedge clk); rstn<=1'b1; end


// -------------------------------------------------------------------------------------------------------------------
//   heartbeat: one minimal line every HEARTBEAT_CYCLES clocks so the outer harness
//   can confirm the simulation is alive without polluting or slowing the run.
// -------------------------------------------------------------------------------------------------------------------
`ifndef HEARTBEAT_CYCLES
`define HEARTBEAT_CYCLES 2000000
`endif
integer hb_cnt = 0;
always @(posedge clk) begin
    hb_cnt <= hb_cnt + 1;
    if(hb_cnt >= `HEARTBEAT_CYCLES) begin
        hb_cnt <= 0;
        $display("  [alive] t=%0t", $time);
    end
end


// -------------------------------------------------------------------------------------------------------------------
//   Optional debug trace: with -D DUMP_EX the testbench writes a per-cycle log of
//   key pipeline signals to ex_trace.txt. Useful for cycle-accurate pre/post-RTL
//   diffs when investigating encoder regressions. No effect when DUMP_EX is unset.
// -------------------------------------------------------------------------------------------------------------------
`ifdef DUMP_EX
integer trace_fp = 0;
initial trace_fp = $fopen("./ex_trace.txt", "w");
always @(posedge clk)
    if(rstn && u_jls_encoder.o_e)
        $fwrite(trace_fp, "fno=%0d o_data=%04x o_last=%0d\n",
            file_no, u_jls_encoder.o_data, u_jls_encoder.o_last);
`endif


// -------------------------------------------------------------------------------------------------------------------
//   signals for jls_encoder module
// -------------------------------------------------------------------------------------------------------------------
reg        i_sof = 0;
reg [13:0] i_w   = 0;
reg [13:0] i_h   = 0;
reg        i_e   = 0;
reg [ 7:0] i_x   = 0;
wire       o_e;
wire       o_last;
wire[15:0] o_data;


reg [7:0] img [8192*8192-1:0];
integer w = 0, h = 0;

task load_img;
    input [256*8:1] fname;
    reg [256*8-1:0] line;
    integer linelen, depth, scanf_num, fp, i, c;
begin
    depth = 0;
    fp = $fopen(fname, "rb");
    if (fp==0)
        $fatal(1, "*** error: could not open file %0s", fname);
    linelen = $fgets(line, fp);
    if (line[8*(linelen-2)+:16] != 16'h5035) begin
        $fclose(fp);
        $fatal(1, "*** error: %0s: the first line must be P5", fname);
    end
    scanf_num = $fgets(line, fp);
    scanf_num = $sscanf(line, "%d%d", w, h);
    if(scanf_num == 1) begin
        scanf_num = $fgets(line, fp);
        scanf_num = $sscanf(line, "%d", h);
    end
    scanf_num = $fgets(line, fp);
    scanf_num = $sscanf(line, "%d", depth);
    if (depth!=255) begin
        $fclose(fp);
        $fatal(1, "*** error: %0s: images depth must be 255", fname);
    end
    for (i=0; i<h*w; i=i+1) begin
        c = $fgetc(fp);
        if (c < 0) begin
            $fclose(fp);
            $fatal(1, "*** error: %0s: truncated pixel data", fname);
        end
        img[i] = c;
    end
    $fclose(fp);
end
endtask


// -------------------------------------------------------------------------------------------------------------------
//   task: feed image pixels to jls_encoder module
// -------------------------------------------------------------------------------------------------------------------
task feed_img;
    input integer bubble_control;
    integer       num_bubble, i;
begin
    repeat(368) begin
        @(posedge clk)
        i_sof <= 1'b1;
        i_w   <= w - 1;
        i_h   <= h - 1;
        {i_e, i_x} <= 0;
    end

    for(i=0; i<h*w; i=i+1) begin
        if(bubble_control<0) begin
            num_bubble = $random % (1-bubble_control);
            if(num_bubble<0) num_bubble = -num_bubble;
        end else begin
            num_bubble = bubble_control;
        end
        repeat(num_bubble) @(posedge clk) {i_sof, i_w, i_h, i_e, i_x} <= 0;
        @(posedge clk)
        {i_sof, i_w, i_h} <= 0;
        i_e <= 1'b1;
        i_x <= img[i];
    end

    repeat(32) @(posedge clk) {i_sof, i_w, i_h, i_e, i_x} <= 0;
end
endtask


// -------------------------------------------------------------------------------------------------------------------
//   jls_encoder instance
// -------------------------------------------------------------------------------------------------------------------
// The regression image set includes 16384-wide vectors, so the default
// instantiates the encoder at the full supported width. run_sim.py can
// override MAX_WIDTH to exercise row cropping of wider images.
jls_encoder #(
    .NEAR      ( `NEAR ),
    .MAX_WIDTH ( `MAX_WIDTH )
) u_jls_encoder (
    .rstn   ( rstn   ),
    .clk    ( clk    ),
    .i_sof  ( i_sof  ),
    .i_w    ( i_w    ),
    .i_h    ( i_h    ),
    .i_e    ( i_e    ),
    .i_x    ( i_x    ),
    .o_e    ( o_e    ),
    .o_last ( o_last ),
    .o_data ( o_data )
);


// -------------------------------------------------------------------------------------------------------------------
//   drive inputs: load and feed all images
// -------------------------------------------------------------------------------------------------------------------
integer file_no;
reg [256*8:1] input_file_name;
reg [256*8:1] input_file_format;

// fed_no[k] is the file number of the k-th frame pushed into the encoder;
// output frame k is named and checked against that entry.
integer fed_no [0:1023];
integer fed_count   = 0;
integer frames_done = 0;
integer wait_cycles;

integer pass_count = 0;
integer fail_count = 0;

initial begin
    $sformat(input_file_format, "%s/%s.pgm", `INPUT_PGM_DIR, `FILE_NAME_FORMAT);

    while(~rstn) @(posedge clk);

    for(file_no=`FILE_NO_FIRST; file_no<=`FILE_NO_FINAL; file_no=file_no+1) begin
        $sformat(input_file_name, input_file_format, file_no);
        load_img(input_file_name);
        $display("  loading %0s (%0dx%0d)", input_file_name, w, h);
        if(w<5 || w>16384 || h<1 || h>16384)
            $display("    *** image size not supported, skipping ***");
        else begin
            fed_no[fed_count] = file_no;
            fed_count = fed_count + 1;
            feed_img(`BUBBLE_CONTROL);
        end
    end

    wait_cycles = 0;
    while(frames_done < fed_count) begin
        @(posedge clk);
        wait_cycles = wait_cycles + 1;
        if(wait_cycles > `FRAME_TIMEOUT_CYCLES)
            $fatal(1, "*** TIMEOUT: %0d of %0d frames completed ***", frames_done, fed_count);
    end
    repeat(200) @(posedge clk);
    if(frames_done != fed_count)
        $fatal(1, "*** %0d frames completed but %0d were fed ***", frames_done, fed_count);

`ifdef SELF_CHECK
    $display("");
    $display("=== SELF-CHECK SUMMARY (NEAR=%0d, MAX_WIDTH=%0d) ===", `NEAR, `MAX_WIDTH);
    $display("  FED  : %0d", fed_count);
    $display("  PASS : %0d", pass_count);
    $display("  FAIL : %0d", fail_count);
    if(fail_count > 0)
        $fatal(1, "*** SELF-CHECK FAILED ***");
    else if(pass_count != fed_count || fed_count == 0)
        $fatal(1, "*** SELF-CHECK FAILED: %0d of %0d frames checked ***", pass_count, fed_count);
    else
        $display("*** ALL CHECKS PASSED ***");
`else
    $display("");
    $display("=== %0d FRAMES WRITTEN to %s ===", frames_done, `OUTPUT_JLS_DIR);
`endif

    $finish;
end


// -------------------------------------------------------------------------------------------------------------------
//   capture output stream: write to file, optionally compare against golden
// -------------------------------------------------------------------------------------------------------------------
reg [256*8:1] out_fmt;
initial $sformat(out_fmt, "%s/%s.jls", `OUTPUT_JLS_DIR, `FILE_NAME_FORMAT);

reg [256*8:1] out_name;
integer       out_fp  = 0;
integer       opened  = 0;

`ifdef SELF_CHECK
reg [256*8:1] gold_fmt;
initial $sformat(gold_fmt, "%s/%s.jls", `GOLDEN_JLS_DIR, `FILE_NAME_FORMAT);
reg [256*8:1] gold_name;
integer       gold_fp      = 0;
integer       mismatch_cnt = 0;
integer       byte_offset  = 0;
integer       gb0, gb1;
`endif

always @(posedge clk)
    if(o_e) begin

        // open output file on first byte of an image
        if(opened == 0) begin
            if(frames_done >= fed_count)
                $fatal(1, "*** output data with no frame in flight (frame %0d, %0d fed) ***",
                       frames_done, fed_count);
            opened = 1;
            $sformat(out_name, out_fmt, fed_no[frames_done]);
            out_fp = $fopen(out_name, "wb");
            if(out_fp == 0)
                $fatal(1, "*** error: could not create %0s ***", out_name);
            `ifdef SELF_CHECK
            mismatch_cnt = 0;
            byte_offset  = 0;
            $sformat(gold_name, gold_fmt, fed_no[frames_done]);
            gold_fp = $fopen(gold_name, "rb");
            if(gold_fp == 0)
                $display("  [FAIL] golden not found: %0s", gold_name);
            `endif
        end

        // write compressed bytes
        $fwrite(out_fp, "%c%c", o_data[7:0], o_data[15:8]);

        // byte-compare against golden
        `ifdef SELF_CHECK
        if(gold_fp != 0) begin
            gb0 = $fgetc(gold_fp);
            if(gb0 !== o_data[7:0]) begin
                if(mismatch_cnt == 0)
                    $display("  [MISMATCH] byte %0d: got 0x%02X expected 0x%02X",
                             byte_offset, o_data[7:0], gb0);
                mismatch_cnt = mismatch_cnt + 1;
            end
            gb1 = $fgetc(gold_fp);
            if(gb1 !== o_data[15:8]) begin
                if(mismatch_cnt == 0)
                    $display("  [MISMATCH] byte %0d: got 0x%02X expected 0x%02X",
                             byte_offset+1, o_data[15:8], gb1);
                mismatch_cnt = mismatch_cnt + 1;
            end
            byte_offset = byte_offset + 2;
        end
        `endif

        // close and report at end of each image
        if(o_last) begin
            opened = 0;
            $fclose(out_fp);
            `ifdef SELF_CHECK
            if(gold_fp != 0) begin
                // the golden must end exactly where the encoder output ends
                if($fgetc(gold_fp) != -1) begin
                    if(mismatch_cnt == 0)
                        $display("  [MISMATCH] output ends at byte %0d, golden is longer", byte_offset);
                    mismatch_cnt = mismatch_cnt + 1;
                end
                $fclose(gold_fp);
                if(mismatch_cnt == 0) begin
                    $display("  [PASS] %0s  (%0d bytes)", out_name, byte_offset);
                    pass_count = pass_count + 1;
                end else begin
                    $display("  [FAIL] %0s  (%0d mismatches in %0d bytes)",
                             out_name, mismatch_cnt, byte_offset);
                    fail_count = fail_count + 1;
                end
            end else begin
                fail_count = fail_count + 1;
            end
            `endif
            frames_done = frames_done + 1;
        end

    end

endmodule
